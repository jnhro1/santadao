-- 마니또 이벤트 초기 스키마 (Postgres, santadao 스키마)
-- 규칙 (.claude/rules/jpa.md)
--   - FK 제약조건은 만들지 않는다
--   - 모든 테이블·컬럼에 한글 COMMENT를 단다
--   - 모든 테이블에 RLS를 켠다 (policy 없음: 앱 계정(테이블 소유자)만 접근, Supabase anon/authenticated 차단)

CREATE TABLE events
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(30)  NOT NULL,
    memo        VARCHAR(200),
    public_code VARCHAR(8)   NOT NULL,
    admin_token VARCHAR(32)  NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_events PRIMARY KEY (id),
    CONSTRAINT uk_events_public_code UNIQUE (public_code),
    CONSTRAINT uk_events_admin_token UNIQUE (admin_token)
);

COMMENT ON TABLE events IS '마니또 이벤트';
COMMENT ON COLUMN events.id IS '이벤트 ID';
COMMENT ON COLUMN events.name IS '이벤트 이름';
COMMENT ON COLUMN events.memo IS '메모 (선물 금액 등)';
COMMENT ON COLUMN events.public_code IS '공용 링크 코드';
COMMENT ON COLUMN events.admin_token IS '주최자 관리 링크 토큰';
COMMENT ON COLUMN events.created_at IS '생성 일시';
COMMENT ON COLUMN events.updated_at IS '수정 일시';

ALTER TABLE events ENABLE ROW LEVEL SECURITY;

CREATE TABLE participants
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id   BIGINT       NOT NULL,
    name       VARCHAR(10)  NOT NULL,
    pin        VARCHAR(4)   NOT NULL,
    manito_id  BIGINT,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_participants PRIMARY KEY (id),
    -- event_id로 시작하므로 이벤트별 참가자 조회 인덱스를 겸한다
    CONSTRAINT uk_participants_event_name UNIQUE (event_id, name)
);

COMMENT ON TABLE participants IS '마니또 참가자';
COMMENT ON COLUMN participants.id IS '참가자 ID';
COMMENT ON COLUMN participants.event_id IS '이벤트 ID (events.id)';
COMMENT ON COLUMN participants.name IS '참가자 이름';
COMMENT ON COLUMN participants.pin IS '결과 확인용 PIN (숫자 4자리)';
COMMENT ON COLUMN participants.manito_id IS '선물할 상대 참가자 ID (participants.id)';
COMMENT ON COLUMN participants.created_at IS '생성 일시';
COMMENT ON COLUMN participants.updated_at IS '수정 일시';

ALTER TABLE participants ENABLE ROW LEVEL SECURITY;
